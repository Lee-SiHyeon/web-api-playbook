const TRAVEL_GOODS = /타월|타올|수건|디퓨저|방향제|베개|이불|침구|토퍼|매트리스|침대|책장|책상|데스크|캐리어|가방|파우치|학습|교재|강의|여행용품/;
const TRAVEL_SERVICE = /항공권|항공편|숙박권|객실|체크인|렌터카|크루즈|\d+\s*박(?!스)\s*(?:\d+\s*일)?/;
const BODY_OR_HOME_PRODUCT = /베개|이불|토퍼|샴푸|린스|트리트먼트|바디워시|핸드워시|비누|클렌저|립밤|헤어팩|마스크팩|(?:콜라겐|수분|보습|핸드|바디|페이스|아이|선)\s*크림/;
const INGREDIENT_WORDS = new Set(['우유', '딸기', '단백질', '프로틴', '콜라겐', '유산균', '오일']);

/** Latin abbreviations are product tokens, not substrings of Frame, Instagram or program. */
function hasKeyword(title: string, word: string): boolean {
  if (/^[a-z0-9]+$/.test(word)) return new RegExp(`(?:^|[^a-z])${word}(?=$|[^a-z])`).test(title);
  return title.includes(word);
}

export function classifyHubTitle(title: string): HubCategory {
  // Promotional brackets describe a discount, not the physical product's category.
  const t = title.normalize('NFKC').toLowerCase().replace(/\[[^\]]*(?:쿠폰|적립|할인|특가|혜택)[^\]]*\]/g, ' ');
  if (/반려견|반려묘|반려동물|강아지|고양이|애견|애묘/.test(t) && /사료|간식|츄르|영양제/.test(t)) return 'pet';
  if (/아기|유아|신생아/.test(t) && /물티슈|샴푸|로션|바디워시|기저귀|분유|젖병|이유식|토퍼/.test(t)) return 'baby';
  const travelAllowed = !TRAVEL_GOODS.test(t) || TRAVEL_SERVICE.test(t);
  const ingredientDescription = BODY_OR_HOME_PRODUCT.test(t);
  let best: HubCategory = 'etc';
  let bestScore = 0;
  for (const [category, words] of KEYWORDS) {
    if (category === 'travel' && !travelAllowed) continue;
    let score = 0;
    for (const w of words) {
      if (category === 'food' && ingredientDescription && INGREDIENT_WORDS.has(w)) continue;
      if (category === 'food' && ingredientDescription && w === '콜라' && t.includes('콜라겐')) continue;
      if (category === 'food' && w === '오레오' && !/\d+\s*g(?:\b|$)|쿠키|과자/.test(t)) continue;
      if (category === 'game' && w === '스팀' && /다리미|청소기|가습기|세탁기|워시타워/.test(t)) continue;
      if (category === 'pc' && w === '토너' && !/프린터|프린트|카트리지|복합기/.test(t)) continue;
      if (category === 'pc' && w === '메모리' && /메모리\s*폼/.test(t)) continue;
      if (category === 'pc' && w === '게이밍' && /의자|책상|데스크/.test(t)) continue;
      if (category === 'fashion' && w === '캡' && /캡슐/.test(t)) continue;
      if (category === 'beauty' && w === '크림' && /아이스크림|생크림|크림\s*(?:빵|과자|쿠키)|오레오.{0,8}크림/.test(t)) continue;
      if (category === 'coupon' && (w === '쿠폰' || w === '적립') && /쿠폰\s*(?:적용|할인)|적립\s*혜택/.test(t)) continue;
      if (hasKeyword(t, w)) score += w.length;
    }
    if (score > bestScore) { best = category; bestScore = score; }
  }
  return best;
}
